def free_slots(niche_key: str, d: date) -> list:
    """Свободное время на день. Часть окон «занята» (стабильно, по хэшу), чтобы демо было живым."""
    n = NICHES[niche_key]
    out = []
    for s in n.slots:
        if zlib.crc32(f"{niche_key}{d.isoformat()}{s}".encode()) % 4 != 0:
            out.append(s)
    return out


def find_service(niche_key: str, name: str):
    """Находит услугу по названию (точно или по вхождению)."""
    name = (name or "").strip().lower()
    for i, s in enumerate(NICHES[niche_key].services):
        if s[0].lower() == name:
            return i, s
    for i, s in enumerate(NICHES[niche_key].services):
        if name and (name in s[0].lower() or s[0].lower() in name):
            return i, s
    return None
