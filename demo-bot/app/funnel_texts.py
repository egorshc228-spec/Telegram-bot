from .funnel_texts_en import EN  # noqa: E402

for _k, _v in EN.items():
    FT[_k]["en"] = _v


def ft(lang: str, key: str, **kw):
    """Текст воронки на языке клиента (uk/ru/en); неизвестный язык — украинский."""
    v = FT[key]
    val = v.get(lang) or v.get("uk")
    if isinstance(val, str) and kw:
        return val.format(**kw)
    return val
